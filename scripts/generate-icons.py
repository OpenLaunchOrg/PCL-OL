#!/usr/bin/env python3
"""Generate OpenLaunch's WPF geometry, PNG and Windows ICO from its polygon SVG."""

import argparse
import math
from pathlib import Path
import struct
import sys
import xml.etree.ElementTree as ET
import zlib

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / "OpenLaunch" / "Images"
SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)


def read_svg():
    svg = ET.parse(IMAGES / "openlaunch.svg").getroot()
    assert svg.attrib["viewBox"] == "0 0 64 64"
    color = svg.attrib["fill"]
    polygons = [
        [tuple(map(float, point.split(","))) for point in node.attrib["points"].split()]
        for node in svg.findall("{http://www.w3.org/2000/svg}polygon")
    ]
    assert polygons, "The icon must contain filled polygons."
    return color, polygons


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def png(size, color, polygons):
    # Rasterize filled polygons at 4x resolution, then box-filter their coverage.
    scale = 4
    width = size * scale
    coverage = bytearray(width * width)
    for polygon in polygons:
        points = [(x * width / 64, y * width / 64) for x, y in polygon]
        edges = list(zip(points, points[1:] + points[:1]))
        for row in range(width):
            y = row + 0.5
            intersections = sorted(
                x1 + (y - y1) * (x2 - x1) / (y2 - y1)
                for (x1, y1), (x2, y2) in edges
                if (y1 <= y < y2) or (y2 <= y < y1)
            )
            for left, right in zip(intersections[::2], intersections[1::2]):
                start = max(0, math.ceil(left - 0.5))
                end = min(width, math.ceil(right - 0.5))
                coverage[row * width + start:row * width + end] = b"\xff" * (end - start)
    rgb = bytes.fromhex(color.lstrip("#"))
    pixels = bytearray()
    for y in range(size):
        pixels.append(0)  # PNG filter: none
        for x in range(size):
            total = sum(
                coverage[(y * scale + dy) * width + x * scale + dx]
                for dy in range(scale) for dx in range(scale)
            )
            pixels.extend(rgb)
            pixels.append(round(total / (scale * scale)))
    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(pixels, 9)) + chunk(b"IEND", b"")


def outputs():
    color, polygons = read_svg()
    frames = [png(size, color, polygons) for size in SIZES]
    offset = 6 + 16 * len(SIZES)
    directory = bytearray(struct.pack("<HHH", 0, 1, len(SIZES)))
    for size, frame in zip(SIZES, frames):
        directory.extend(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(frame), offset))
        offset += len(frame)
    geometry = "F1 " + " ".join(
        "M " + " L ".join(f"{x:g},{y:g}" for x, y in polygon) + " Z"
        for polygon in polygons
    )
    xaml = f'''<!-- Generated by scripts/generate-icons.py from Images/openlaunch.svg. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
    <Geometry x:Key="OpenLaunchIconGeometry">{geometry}</Geometry>
    <DrawingImage x:Key="OpenLaunchIcon">
        <DrawingImage.Drawing>
            <GeometryDrawing Brush="{color}" Geometry="{{StaticResource OpenLaunchIconGeometry}}" />
        </DrawingImage.Drawing>
    </DrawingImage>
</ResourceDictionary>
'''
    return {
        IMAGES / "icon.ico": bytes(directory) + b"".join(frames),
        IMAGES / "openlaunch.png": frames[-1],
        ROOT / "OpenLaunch" / "Resources" / "Branding.xaml": xaml.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated assets differ from the SVG.")
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            current = path.read_bytes() if path.exists() else None
            # Git may check text files out with CRLF on Windows.
            if current is not None and path.suffix == ".xaml":
                current = current.replace(b"\r\n", b"\n")
            if current != data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(data)
            print(f"Generated {path.relative_to(ROOT)}")
    if stale:
        print("Stale assets: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("OpenLaunch vector and Windows icon assets are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
